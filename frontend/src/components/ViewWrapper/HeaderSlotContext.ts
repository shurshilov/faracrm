import { createContext, useContext } from 'react';

/**
 * Слот в шапке ViewWrapper для контролов активного вида.
 *
 * Значение — DOM-узел в правой части шапки (рядом с поиском и
 * переключателем видов). Активный вид (например список) телепортирует
 * туда свои контролы через `createPortal` — так меню «⋮» списка (колонки,
 * Excel) живёт в верхней панели, но остаётся собственностью списка:
 * появляется только когда список смонтирован, и исчезает на канбане/
 * гантте/форме (там в слот никто ничего не кладёт).
 *
 * null — провайдера нет (List используется вне ViewWrapper). В этом случае
 * List показывает контрол в собственном тулбаре (фолбэк, без регрессии).
 */
export const HeaderSlotContext = createContext<HTMLElement | null>(null);

export const useHeaderSlot = () => useContext(HeaderSlotContext);
