-- Встроенные папки («Все»/«Личные»/«Группы», внешние «Все»/«Мои») и
-- автопапки коннекторов (в т.ч. «Web Push») больше не нужны: разделы
-- считает бэкенд (Chat.SECTION_SQL), источник — чип над списком. Без поля
-- kind/connector_id в модели такие строки — папки без фильтра: каждая
-- показывала бы все чаты отдельным общим квадратом.
-- Свои папки пользователей (kind и connector_id пустые) не трогаем.
DELETE FROM chat_folder WHERE kind IS NOT NULL OR connector_id IS NOT NULL;

-- Колонки больше не читаются, а dotorm сам их не удаляет.
ALTER TABLE chat_folder DROP COLUMN IF EXISTS kind;
ALTER TABLE chat_folder DROP COLUMN IF EXISTS connector_id;
